import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { checkVersions, prepareRelease, readVersionManifest, releaseTags, renderChangelog,
  syncVersions, validateVersionManifest, versionSummary } from '../../scripts/versioning.mjs';

const SERIALIZE = (value) => JSON.stringify(value, null, 2) + '\n';
const DESKTOP = 'apps/framework/desktop/src-tauri';
const SOURCE = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const initial = () => ({ schemaVersion: 1,
  features: [{ id: 'core.workbench', name: '工作台', module: 'framework' }],
  releases: [{ version: '0.1.0', date: '2026-10-17', summary: '首版工作台',
    changes: [{ featureId: 'core.workbench', version: '0.1.0', type: 'added', description: '建立桌面工作台。' }] }] });
const draft = () => ({ version: '0.2.0', date: '2026-10-18', summary: '加入分析功能',
  features: [{ id: 'tower.layout', name: '布局分析', module: 'tower-assistant' }],
  changes: [{ featureId: 'core.workbench', version: '0.1.1', type: 'fixed', description: '修复关闭行为。' },
    { featureId: 'tower.layout', version: '0.1.0', type: 'added', description: '分析布局。' }] });

function fixture(t) {
  const root = fs.mkdtempSync(join(tmpdir(), 'nimdadesk-version-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(join(root, 'config'), { recursive: true });
  fs.mkdirSync(join(root, DESKTOP), { recursive: true });
  fs.writeFileSync(join(root, 'config/version.json'), SERIALIZE(initial()));
  fs.writeFileSync(join(root, 'package.json'), SERIALIZE({ name: 'nimdadesk', version: '0.1.0', scripts: { unchanged: 'yes' } }));
  fs.writeFileSync(join(root, 'package-lock.json'), SERIALIZE({ name: 'nimdadesk', version: '0.1.0', lockfileVersion: 3,
    packages: { '': { name: 'nimdadesk', version: '0.1.0' }, 'node_modules/dependency': { version: '7.8.9' } } }));
  fs.writeFileSync(join(root, `${DESKTOP}/tauri.conf.json`), SERIALIZE({ productName: 'NimdaDesk', version: '0.1.0', identifier: 'example.test' }));
  fs.writeFileSync(join(root, `${DESKTOP}/Cargo.toml`), '[package]\nname = "nimdadesk"\nversion = "0.1.0"\n\n[dependencies]\nthing = { version = "3.4.5" }\n');
  fs.writeFileSync(join(root, `${DESKTOP}/Cargo.lock`), '# Generated by Cargo\nversion = 4\n\n[[package]]\nname = "another"\nversion = "4.5.6"\n\n[[package]]\nname = "nimdadesk"\nversion = "0.1.0"\ndependencies = ["another"]\n\n[[package]]\nname = "tail"\nversion = "1.2.3"\n');
  return root;
}

function contents(root) {
  const result = {};
  for (const entry of fs.readdirSync(root, { recursive: true, withFileTypes: true })) {
    if (entry.isFile()) {
      const path = join(entry.parentPath, entry.name);
      result[path.slice(root.length + 1)] = fs.readFileSync(path).toString('base64');
    }
  }
  return result;
}

function fullHistory(change = draft()) {
  const manifest = initial();
  const { features = [], ...release } = change;
  manifest.features.push(...features);
  manifest.releases.unshift(release);
  return manifest;
}

test('prepare synchronizes every application version and replays independent feature history', (t) => {
  const root = fixture(t);
  assert.deepEqual(syncVersions(root).changedFiles, ['CHANGELOG.md']);
  const result = prepareRelease(root, draft());
  assert.equal(result.appVersion, '0.2.0');
  assert.equal(result.changedFiles.length, 7);
  assert.deepEqual(checkVersions(root).features.map(({ id, version, updatedIn }) => ({ id, version, updatedIn })), [
    { id: 'core.workbench', version: '0.1.1', updatedIn: '0.2.0' },
    { id: 'tower.layout', version: '0.1.0', updatedIn: '0.2.0' },
  ]);
  const npm = JSON.parse(fs.readFileSync(join(root, 'package.json')));
  const lock = JSON.parse(fs.readFileSync(join(root, 'package-lock.json')));
  assert.equal(npm.version, '0.2.0');
  assert.equal(npm.scripts.unchanged, 'yes');
  assert.equal(lock.version, '0.2.0');
  assert.equal(lock.packages[''].version, '0.2.0');
  assert.equal(lock.packages['node_modules/dependency'].version, '7.8.9');
  assert.match(fs.readFileSync(join(root, `${DESKTOP}/Cargo.lock`), 'utf8'), /name = "nimdadesk"\nversion = "0.2.0"/);
  assert.match(fs.readFileSync(join(root, `${DESKTOP}/Cargo.lock`), 'utf8'), /name = "another"\nversion = "4.5.6"/);
  assert.match(fs.readFileSync(join(root, `${DESKTOP}/Cargo.toml`), 'utf8'), /thing = \{ version = "3.4.5" \}/);
  assert.equal(fs.readFileSync(join(root, 'CHANGELOG.md'), 'utf8'), renderChangelog(readVersionManifest(root)));
  assert.deepEqual(syncVersions(root).changedFiles, []);
});

test('unchanged feature versions stay unchanged and tags include only the current release', () => {
  const manifest = fullHistory();
  manifest.releases.unshift({ version: '0.2.1', date: '2026-10-18', summary: '修复布局',
    changes: [{ featureId: 'tower.layout', version: '0.1.1', type: 'fixed', description: '修复显示。' }] });
  const summary = versionSummary(manifest);
  assert.equal(summary.features[0].updatedIn, '0.2.0');
  assert.equal(summary.features[0].version, '0.1.1');
  assert.equal(summary.features[1].updatedIn, '0.2.1');
  assert.deepEqual(releaseTags(manifest), ['v0.2.1', 'feature/tower.layout/v0.1.1']);
});

test('failed validation never writes any file', (t) => {
  const root = fixture(t);
  syncVersions(root);
  const before = contents(root);
  const value = draft();
  value.changes[0].version = '0.1.2';
  assert.throws(() => prepareRelease(root, value), /跳档/);
  assert.deepEqual(contents(root), before);
});

test('preflight parses all files before modifying any earlier version target', (t) => {
  const root = fixture(t);
  syncVersions(root);
  fs.writeFileSync(join(root, `${DESKTOP}/Cargo.lock`), 'corrupt');
  const before = contents(root);
  assert.throws(() => prepareRelease(root, draft()), /唯一/);
  assert.deepEqual(contents(root), before);
});

test('write failure rolls back original bytes and removes staging files', (t) => {
  const root = fixture(t);
  syncVersions(root);
  const before = contents(root);
  const original = fs.renameSync;
  let calls = 0;
  fs.renameSync = (...args) => {
    if (++calls === 3) throw new Error('simulated replace failure');
    return original(...args);
  };
  try { assert.throws(() => prepareRelease(root, draft()), /simulated replace failure/); }
  finally { fs.renameSync = original; }
  assert.equal(calls, 3);
  assert.deepEqual(contents(root), before);
});

test('check detects application lockfile drift and exact changelog drift', (t) => {
  const root = fixture(t);
  syncVersions(root);
  const path = join(root, 'package-lock.json');
  const lock = JSON.parse(fs.readFileSync(path));
  lock.packages[''].version = '0.9.0';
  fs.writeFileSync(path, SERIALIZE(lock));
  assert.throws(() => checkVersions(root), /package-lock/);
  syncVersions(root);
  fs.appendFileSync(join(root, 'CHANGELOG.md'), '\nmanual change\n');
  assert.throws(() => checkVersions(root), /CHANGELOG/);
  const before = contents(root);
  assert.throws(() => prepareRelease(root, draft()), /CHANGELOG/);
  assert.deepEqual(contents(root), before);
});

